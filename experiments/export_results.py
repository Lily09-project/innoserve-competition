"""Export aggregates only and bind supplementary evidence to exact sources."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'app'))
from provenance import code_revision

SOURCES = ['experiments/' + name for name in ('common.py', 'ablation.py', 'retrieval_sensitivity.py',
           'service_poc.py', 'ssh_endpoint.py', 'latency.py', 'export_results.py')]
RESULTS = ['results/' + name for name in ('auditor_ablation.json', 'retrieval_sensitivity.json',
           'ssh_service_poc.json', 'pipeline_latency.json')]


def sha(path):
    content = Path(path).read_bytes()
    if Path(path).suffix in ('.py', '.json'):
        content = content.replace(b'\r\n', b'\n')
    return hashlib.sha256(content).hexdigest()


def bindings(root):
    return {name: sha(root / name) for name in SOURCES + RESULTS}


def verify(root=ROOT):
    root = Path(root)
    index = json.loads((root / 'results/supplementary_validation.json').read_text(encoding='utf-8'))
    if index['bindings'] != bindings(root) or index['source_revision'] != code_revision(root):
        raise ValueError('supplementary_evidence_binding_mismatch')
    read = lambda name: json.loads((root / 'results' / name).read_text(encoding='utf-8'))
    audit = read('auditor_ablation.json')
    if audit['status'] != 'passed' or audit['protocol']['cases'] != 463 or len(audit['arms']) != 5:
        raise ValueError('incomplete_ablation')
    for name, arm in audit['arms'].items():
        if arm['cases'] != 463 or sum(arm[key] for key in ('support', 'review', 'uncertain')) != 463:
            raise ValueError('invalid_ablation_counts')
        if arm['wrong_support'] + arm['correct_support'] != arm['support']:
            raise ValueError('invalid_support_counts')
        if arm['fresh_llm_calls'] != (463 if name.startswith('llm_') else 0):
            raise ValueError('invalid_fresh_calls')
        if arm['classification_changed_count'] or arm['network_actions_executed']:
            raise ValueError('ablation_scope_changed')
    service = read('ssh_service_poc.json')
    if len(service['trials']) != 3 or not service['cleanup']['passed']:
        raise ValueError('incomplete_service_trials')
    for trial in service['trials']:
        if not trial['rollback_empty'] or not 30 <= trial['ttl_rollback_seconds'] <= 32:
            raise ValueError('service_rollback_failed')
        for key in ('baseline_valid_subject', 'baseline_valid_background', 'limited_valid_background', 'recovered_subject', 'recovered_background'):
            if trial[key]['healthy'] != trial[key]['attempts']:
                raise ValueError('normal_service_or_recovery_failed')
    sensitivity = read('retrieval_sensitivity.json')
    if len(sensitivity['trials']) != 30 or sensitivity['protocol']['train_query_id_overlap'] != 0:
        raise ValueError('invalid_sensitivity_trials')
    latency = read('pipeline_latency.json')
    if latency['warm_calls'] != 306 or len(latency['processes']) != 3 or latency['classification_mismatches'] != 0:
        raise ValueError('incomplete_latency_trials')
    return True


def build(folder):
    read = lambda name: json.loads((folder / name).read_text(encoding='utf-8'))
    audit = read('supplementary-ablation-20261029/summary.json')
    sensitivity = read('retrieval-sensitivity-20261029.json')
    service_raw = read('ssh-service-final-20261029/summary.json')
    timing_raw = read('latency-processes-20261029/summary.json')
    if audit['protocol']['source_revision'] != code_revision() or service_raw['source_revision'] != code_revision():
        raise ValueError('experiment_core_revision_mismatch')
    for arm, recorded in audit['raw_record_sha256'].items():
        path = folder / 'supplementary-ablation-20261029' / (arm + '.jsonl')
        if sha(path) != recorded:
            raise ValueError('ablation_raw_record_changed')
        records = [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines()]
        if len(records) != 463 or len({r['event_id'] for r in records}) != 463:
            raise ValueError('ablation_raw_count_mismatch')
    # Reject outputs generated by different versions rather than rebinding old runs.
    for name, recorded in audit['protocol']['experiment_sources'].items():
        if recorded != sha(ROOT / 'experiments' / name):
            raise ValueError('ablation_source_changed')
    for name, recorded in service_raw['experiment_sources'].items():
        if recorded != sha(ROOT / 'experiments' / name):
            raise ValueError('service_source_changed')
    if sensitivity['protocol']['script_sha256'] != sha(ROOT / 'experiments/retrieval_sensitivity.py'):
        raise ValueError('sensitivity_source_changed')
    service = {key: value for key, value in service_raw.items() if key != 'trials'}
    service['trials'] = [{key: value for key, value in row.items() if key != 'rule_readback'} for row in service_raw['trials']]
    processes = []
    rows = []
    for run in timing_raw['runs']:
        if run['source_revision'] != code_revision() or run['asset_revision'] != audit['protocol']['asset_revision']:
            raise ValueError('latency_runtime_revision_mismatch')
        processes.append({key: value for key, value in run.items() if key != 'warm'})
        rows.extend(run['warm'])
    import numpy as np
    elapsed = [r['elapsed_ms'] for r in rows]
    timing = {'status': 'completed', 'processes': processes, 'warm_calls': len(rows), 'unique_inputs': 17,
              'warm_p50_ms': float(np.percentile(elapsed, 50)), 'warm_p95_ms': float(np.percentile(elapsed, 95)),
              'warm_min_ms': min(elapsed), 'warm_max_ms': max(elapsed),
              'serial_calls_per_second': len(rows) / (sum(elapsed) / 1000),
              'classification_mismatches': sum(not r['classification_matches_saved'] for r in rows),
              'scope': timing_raw['scope'],
              'quantile_method': 'numpy.percentile linear; pooled 306 serial measured calls',
              'stage_timings': {key: {'p50_ms': float(np.percentile([r['timings'][key] for r in rows], 50)),
                                      'p95_ms': float(np.percentile([r['timings'][key] for r in rows], 95))}
                                for key in ('detector_ms', 'retrieval_ms', 'fresh_llm_ms')}}
    for path, report in zip(RESULTS, (audit, sensitivity, service, timing)):
        (ROOT / path).write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    private_paths = ['supplementary-ablation-20261029/summary.json', 'retrieval-sensitivity-20261029.json',
                     'ssh-service-final-20261029/summary.json', 'latency-processes-20261029/summary.json']
    index = {'created_utc': datetime.now(timezone.utc).isoformat(), 'source_revision': code_revision(),
             'bindings': bindings(ROOT), 'private_summary_sha256': {str(i + 1): sha(folder / name) for i, name in enumerate(private_paths)},
             'private_ablation_records_sha256': audit['raw_record_sha256'],
             'scope': 'Supplementary aggregates only. Historical production experiment and native presentation assets unchanged.'}
    (ROOT / 'results/supplementary_validation.json').write_text(json.dumps(index, indent=2) + '\n', encoding='utf-8')
    verify()


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--build-from', type=Path)
    args = parser.parse_args()
    if args.build_from:
        build(args.build_from)
    else:
        verify()
    print('SUPPLEMENTARY_EVIDENCE_VERIFIED')
